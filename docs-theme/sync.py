"""Copy the aesop docs theme into every sibling tool repo that has mdBook docs.

    uv run python docs-theme/sync.py            # write
    uv run python docs-theme/sync.py --check    # exit 1 if any copy is stale

For each tool in content/tools.yaml with a ../<repo>/docs/book.toml this writes
docs/custom.css, docs/aesop.js and docs/theme/head.hbs. book.toml must list
custom.css in additional-css and aesop.js in additional-js; the script says so
when it does not. Commit and push each tool repo yourself.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).parent
ROOT = HERE.parent
FONTS = (
    '<link rel="preconnect" href="https://fonts.googleapis.com">\n'
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
    '<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800'
    '&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet">\n'
)


def repo_dir(tool: dict) -> Path:
    """Local checkout for a tool: ~/git/<last segment of its repo URL>, or `dir:` override."""
    name = tool.get("dir") or tool["links"]["repo"].rstrip("/").rsplit("/", 1)[-1]
    return ROOT.parent / name


def head_hbs(tool: dict, base_url: str) -> str:
    cfg = {
        "name": tool["name"],
        "animal": tool["animal"],
        "tagline": tool["tagline"],
        "home": f"{base_url}/",
        "page": f"{base_url}/{tool['id']}/",
        "mascot": f"{base_url}/static/img/{tool['id']}.webp",
    }
    return (
        "<!-- GENERATED by mojzis/aesop docs-theme/sync.py — do not edit here. -->\n"
        + FONTS
        + f"<style>:root {{ --accent: {tool['accent']}; }}</style>\n"
        + f"<script>window.AESOP = {json.dumps(cfg, ensure_ascii=False)};</script>\n"
    )


def main() -> int:
    check = "--check" in sys.argv
    site = yaml.safe_load((ROOT / "content/site.yaml").read_text())
    tools = yaml.safe_load((ROOT / "content/tools.yaml").read_text())
    css = (HERE / "aesop-docs.css").read_text()
    js = (HERE / "aesop-docs.js").read_text()
    stale = 0
    for tool in tools:
        docs = repo_dir(tool) / "docs"
        book = docs / "book.toml"
        if not book.exists():
            continue
        wanted = {
            docs / "custom.css": css,
            docs / "aesop.js": js,
            docs / "theme/head.hbs": head_hbs(tool, site["base_url"]),
        }
        changed = [p for p, text in wanted.items() if not p.exists() or p.read_text() != text]
        if not check:
            for p in changed:
                p.parent.mkdir(exist_ok=True)
                p.write_text(wanted[p])
        stale += len(changed)
        state = ("STALE" if check else "wrote") if changed else "ok"
        print(f"{tool['id']:12} {state:6} {' '.join(p.name for p in changed)}")
        toml = book.read_text()
        for needle in ('"aesop.js"', '"custom.css"'):
            if needle not in toml:
                print(f"{'':12} book.toml does not list {needle}")
                stale += check
    return 1 if check and stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
